export const questionsEn: Question[] = questions.map((q, index) => {
  const seed = englishSeeds[index]!;
  const names = new Map(
    questions.map((item, i) => [
      item.options[item.correct]!.label,
      englishSeeds[i]!,
    ]),
  );
  return {
    ...q,
    theme: seed[1],
    title: "What is the most likely diagnosis?",
    context: seed[2],
    clues: seed[3],
    reasoning: seed[4],
    takeaway: seed[5],
    objective: `Recognize ${seed[0].toLowerCase()} from discriminating clinical clues.`,
    options: q.options.map((o, i) => ({
      label: names.get(o.label)![0],
      explanation:
        i === q.correct
          ? seed[4]
          : `This diagnosis does not explain the full combination of clues as well: ${seed[3].join(", ").toLowerCase()}. For comparison: ${names.get(o.label)![4]}`,
    })),
    sources: q.sources.map((s) => ({
      ...s,
      title:
        index < 10
          ? "DermNet — dermatology resources (medical review pending)"
          : "MSD Manual — clinical resources (medical review pending)",
    })),
  };
});
